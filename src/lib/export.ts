import { PDFDocument, rgb, StandardFonts } from "pdf-lib";

/**
 * Converts a table dataset to a standard CSV string with proper RFC 4180 escaping
 */
export function generateCsvString(headers: string[], rows: (string | number | null | undefined)[][]): string {
  const escapeCell = (val: string | number | null | undefined): string => {
    if (val === null || val === undefined) return '""';
    const str = String(val);
    if (str.includes('"') || str.includes(',') || str.includes('\n')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const headerLine = headers.map(escapeCell).join(",");
  const dataLines = rows.map((row) => row.map(escapeCell).join(","));
  return [headerLine, ...dataLines].join("\r\n");
}

/**
 * Triggers a browser download of a CSV file
 */
export function downloadCsv(filename: string, headers: string[], rows: (string | number | null | undefined)[][]): void {
  const csvContent = generateCsvString(headers, rows);
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", filename.endsWith(".csv") ? filename : `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generates an official tabular PDF report using pdf-lib
 */
export async function generateTabularReportPdf(params: {
  title: string;
  subtitle?: string;
  campusName?: string;
  generatedDate?: string;
  headers: string[];
  rows: (string | number | null | undefined)[][];
}): Promise<Uint8Array> {
  const { title, subtitle, campusName = "Delhi-NCR Campus", generatedDate = new Date().toISOString().substring(0, 10), headers, rows } = params;

  const pdfDoc = await PDFDocument.create();
  let page = pdfDoc.addPage([595.28, 841.89]); // A4 portrait
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  const fontRegular = await pdfDoc.embedFont(StandardFonts.Helvetica);

  const margin = 40;
  const pageWidth = 595.28;
  const contentWidth = pageWidth - margin * 2;
  let y = 800;

  // Header banner
  page.drawText("TRACK STACK • MIRAI SCHOOL OF TECHNOLOGY", {
    x: margin,
    y,
    size: 9,
    font: fontBold,
    color: rgb(0.13, 0.83, 0.93), // Cyan
  });
  y -= 22;

  page.drawText(title, {
    x: margin,
    y,
    size: 18,
    font: fontBold,
    color: rgb(0.06, 0.09, 0.16),
  });
  y -= 14;

  if (subtitle) {
    page.drawText(subtitle, {
      x: margin,
      y,
      size: 10,
      font: fontRegular,
      color: rgb(0.35, 0.42, 0.52),
    });
    y -= 14;
  }

  page.drawText(`Campus: ${campusName}  •  Report Date: ${generatedDate}`, {
    x: margin,
    y,
    size: 8,
    font: fontRegular,
    color: rgb(0.45, 0.52, 0.62),
  });
  y -= 20;

  // Divider
  page.drawLine({
    start: { x: margin, y },
    end: { x: pageWidth - margin, y },
    thickness: 1,
    color: rgb(0.85, 0.88, 0.93),
  });
  y -= 15;

  // Calculate column widths
  const colCount = headers.length;
  const colWidth = contentWidth / colCount;

  // Draw Table Headers
  page.drawRectangle({
    x: margin,
    y: y - 4,
    width: contentWidth,
    height: 18,
    color: rgb(0.94, 0.96, 0.99),
  });

  headers.forEach((h, i) => {
    page.drawText(String(h), {
      x: margin + i * colWidth + 4,
      y,
      size: 8,
      font: fontBold,
      color: rgb(0.1, 0.15, 0.25),
    });
  });
  y -= 18;

  // Draw Rows
  const maxRowsPerPage = 38;
  let rowCount = 0;

  for (const row of rows) {
    if (rowCount > 0 && rowCount % maxRowsPerPage === 0) {
      page = pdfDoc.addPage([595.28, 841.89]);
      y = 800;
    }

    if (rowCount % 2 === 1) {
      page.drawRectangle({
        x: margin,
        y: y - 3,
        width: contentWidth,
        height: 14,
        color: rgb(0.98, 0.99, 1.0),
      });
    }

    row.forEach((cell, i) => {
      const text = cell !== null && cell !== undefined ? String(cell) : "-";
      page.drawText(text.length > 28 ? `${text.substring(0, 26)}...` : text, {
        x: margin + i * colWidth + 4,
        y,
        size: 7.5,
        font: fontRegular,
        color: rgb(0.15, 0.2, 0.3),
      });
    });

    y -= 14;
    rowCount++;
  }

  // Footer
  page.drawText("Generated by Track Stack Compliance Engine. Cryptographically verifiable.", {
    x: margin,
    y: 25,
    size: 7.5,
    font: fontRegular,
    color: rgb(0.55, 0.6, 0.7),
  });

  return await pdfDoc.save();
}
